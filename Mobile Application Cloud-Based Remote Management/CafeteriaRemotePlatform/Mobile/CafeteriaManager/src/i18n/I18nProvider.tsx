export type TranslationKey = keyof typeof translations.en;

type I18nValue = {
  language: 'ar' | 'en';
  isRTL: boolean;
  setLanguage: (language: 'ar' | 'en') => Promise<void>;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  textAlign: 'left' | 'right';
  rowDirection: 'row' | 'row-reverse';
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<'ar' | 'en'>(
    getLocales()[0]?.languageCode === 'ar' ? 'ar' : 'en'
  );

  useEffect(() => {
    let active = true;
    getStoredLanguage()
      .then((stored) => {
        if (active && stored) setLanguageState(stored);
      })
      .catch(() => undefined);
    I18nManager.allowRTL(true);
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback(async (next: 'ar' | 'en') => {
    setLanguageState(next);
    await saveLanguage(next);
    await AsyncStorage.setItem('cafeteria.manager.direction', next === 'ar' ? 'rtl' : 'ltr');
  }, []);

  const value = useMemo<I18nValue>(() => {
    const isRTL = language === 'ar';
    return {
      language,
      isRTL,
      setLanguage,
      textAlign: isRTL ? 'right' : 'left',
      rowDirection: isRTL ? 'row-reverse' : 'row',
      t: (key, params) => {
        let text: string = translations[language][key] ?? translations.en[key] ?? key;
        if (params) {
          for (const [name, replacement] of Object.entries(params)) {
            text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement));
          }
        }
        return text;
      }
    };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider.');
  return value;
}
